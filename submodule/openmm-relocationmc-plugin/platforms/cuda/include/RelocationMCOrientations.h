#ifndef OPENMM_RELOCATIONMC_ORIENTATIONS_H_
#define OPENMM_RELOCATIONMC_ORIENTATIONS_H_

/* Prepared Orientations are adapted from https://github.com/MartinWeigel/Quaternion
 * The 60 quaternions form a deterministic finite orientation proposal set.
 * Stored decimal values are normalized before constructing rotation matrices.
 */

#include "openmm/Vec3.h"
#include <array>
#include <cassert>
#include <cmath>
#include <vector>

namespace OpenMM {
namespace RelocationMCPlugin {

class PreparedOrientations {
public:
    PreparedOrientations() {
        static const double values[60][4] = {
            {1.000000,0.000000,0.000000,0.000000},
            {0.000000,1.000000,0.000000,0.000000},
            {0.000000,0.000000,1.000000,0.000000},
            {0.000000,0.000000,0.000000,1.000000},
            {0.000000,0.500000,0.309017,0.809017},
            {0.000000,-0.500000,0.309017,0.809017},
            {0.000000,0.500000,-0.309017,0.809017},
            {-0.000000,-0.500000,-0.309017,0.809017},
            {0.000000,0.309017,0.809017,0.500000},
            {0.000000,-0.309017,0.809017,0.500000},
            {-0.000000,-0.309017,0.809017,-0.500000},
            {0.000000,0.309017,0.809017,-0.500000},
            {0.000000,0.809017,0.500000,0.309017},
            {-0.000000,0.809017,-0.500000,-0.309017},
            {0.000000,0.809017,-0.500000,0.309017},
            {0.000000,0.809017,0.500000,-0.309017},
            {0.500000,0.000000,0.809017,0.309017},
            {-0.500000,0.000000,0.809017,0.309017},
            {-0.500000,-0.000000,0.809017,-0.309017},
            {0.500000,0.000000,0.809017,-0.309017},
            {0.309017,0.000000,0.500000,0.809017},
            {-0.309017,0.000000,0.500000,0.809017},
            {0.309017,0.000000,-0.500000,0.809017},
            {-0.309017,-0.000000,-0.500000,0.809017},
            {0.809017,0.000000,0.309017,0.500000},
            {0.809017,-0.000000,-0.309017,-0.500000},
            {0.809017,0.000000,-0.309017,0.500000},
            {0.809017,0.000000,0.309017,-0.500000},
            {0.309017,0.809017,0.000000,0.500000},
            {-0.309017,0.809017,0.000000,0.500000},
            {-0.309017,0.809017,-0.000000,-0.500000},
            {0.309017,0.809017,0.000000,-0.500000},
            {0.809017,0.500000,0.000000,0.309017},
            {0.809017,-0.500000,-0.000000,-0.309017},
            {0.809017,-0.500000,0.000000,0.309017},
            {0.809017,0.500000,0.000000,-0.309017},
            {0.500000,0.309017,0.000000,0.809017},
            {-0.500000,0.309017,0.000000,0.809017},
            {0.500000,-0.309017,0.000000,0.809017},
            {-0.500000,-0.309017,-0.000000,0.809017},
            {0.809017,0.309017,0.500000,0.000000},
            {0.809017,-0.309017,-0.500000,-0.000000},
            {0.809017,-0.309017,0.500000,0.000000},
            {0.809017,0.309017,-0.500000,0.000000},
            {0.500000,0.809017,0.309017,0.000000},
            {-0.500000,0.809017,0.309017,0.000000},
            {-0.500000,0.809017,-0.309017,-0.000000},
            {0.500000,0.809017,-0.309017,0.000000},
            {0.309017,0.500000,0.809017,0.000000},
            {-0.309017,0.500000,0.809017,0.000000},
            {0.309017,-0.500000,0.809017,0.000000},
            {-0.309017,-0.500000,0.809017,-0.000000},
            {0.500000,0.500000,0.500000,0.500000},
            {0.500000,-0.500000,-0.500000,-0.500000},
            {0.500000,-0.500000,0.500000,0.500000},
            {0.500000,0.500000,-0.500000,0.500000},
            {0.500000,0.500000,0.500000,-0.500000},
            {0.500000,0.500000,-0.500000,-0.500000},
            {0.500000,-0.500000,0.500000,-0.500000},
            {0.500000,-0.500000,-0.500000,0.500000}
        };
        matrices.resize(60);
        for (int i = 0; i < 60; i++) {
            const double norm = std::sqrt(values[i][0]*values[i][0]+values[i][1]*values[i][1]+
                    values[i][2]*values[i][2]+values[i][3]*values[i][3]);
            assert(norm > 0.0);
            const double w = values[i][0]/norm;
            const double x = values[i][1]/norm;
            const double y = values[i][2]/norm;
            const double z = values[i][3]/norm;
            matrices[i] = {
                Vec3(1-2*y*y-2*z*z, 2*x*y-2*w*z, 2*x*z+2*w*y),
                Vec3(2*x*y+2*w*z, 1-2*x*x-2*z*z, 2*y*z-2*w*x),
                Vec3(2*x*z-2*w*y, 2*y*z+2*w*x, 1-2*x*x-2*y*y)
            };
        }
    }

    int size() const {
        return (int) matrices.size();
    }

    const std::array<Vec3, 3>& getRotationMatrix(int index) const {
        return matrices.at(index);
    }

    Vec3 rotate(int index, const Vec3& position) const {
        const std::array<Vec3, 3>& matrix = getRotationMatrix(index);
        return matrix[0]*position[0]+matrix[1]*position[1]+matrix[2]*position[2];
    }

private:
    std::vector<std::array<Vec3, 3> > matrices;
};

} // namespace RelocationMCPlugin
} // namespace OpenMM

#endif
